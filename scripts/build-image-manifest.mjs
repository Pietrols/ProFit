// Lists ProFit's own exercise images so the app can bundle them.
//
//   node scripts/build-image-manifest.mjs
//
// Reads mobile/assets/exercises/<exercise id>.webp (or .jpg/.png) and writes
// mobile/src/features/exercises/data/images.ts. Metro needs a literal require() per file, which is
// why this is generated. Fails on a file whose name is not an exercise id. See docs/IMAGE_GUIDE.md.

import { readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, extname, basename, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const ASSETS = join(ROOT, 'mobile/assets/exercises');
const LIBRARY = join(ROOT, 'mobile/src/features/exercises/data/library.json');
const OUTPUT = join(ROOT, 'mobile/src/features/exercises/data/images.ts');
const EXTENSIONS = new Set(['.webp', '.jpg', '.jpeg', '.png']);

const ids = new Set(JSON.parse(await readFile(LIBRARY, 'utf8')).exercises.map((x) => x.id));
const files = (await readdir(ASSETS)).filter((f) => EXTENSIONS.has(extname(f).toLowerCase())).sort();

const seen = new Set();
const unknown = [];
for (const f of files) {
  const id = basename(f, extname(f));
  if (!ids.has(id)) unknown.push(f);
  if (seen.has(id)) throw new Error(`Two images for ${id}`);
  seen.add(id);
}
if (unknown.length) throw new Error(`Not exercise ids (rename to match library.json): ${unknown.join(', ')}`);

const lines = files.map((f) => `  ${JSON.stringify(basename(f, extname(f)))}: require('../../../../assets/exercises/${f}'),`);
const body = lines.length ? `{\n${lines.join('\n')}\n}` : '{}';
await writeFile(
  OUTPUT,
  `// Generated by scripts/build-image-manifest.mjs. Do not edit.\n\nexport const exerciseImages: Record<string, number> = ${body};\n`,
);
console.log(`Wrote ${files.length} images of ${ids.size} exercises to ${OUTPUT}`);
